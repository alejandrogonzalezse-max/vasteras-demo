const stars = (pts: [number, number][]): R[] => pts.map(([x, y]) => [x, y, 1, 1, P.star]);

/** Rutmönster: fyller en yta med rutor av storlek s i färgen c (varannan ruta). */
function checks(x0: number, y0: number, w: number, h: number, s: number, c: string): R[] {
	const out: R[] = [];
	for (let y = 0; y < h; y += s)
		for (let x = 0; x < w; x += s)
			if (((x + y) / s) % 2 === 0) out.push([x0 + x, y0 + y, Math.min(s, w - x), Math.min(s, h - y), c]);
	return out;
}

